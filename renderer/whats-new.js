  function escapeHtml(value) {
    return String(value == null ? "" : value)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  }

  function formatBodyHtml(body) {
    return escapeHtml(body).replace(/\n/g, "<br>");
  }

  function compareVersions(a, b) {
    var pa = String(a || "0")
      .split(".")
      .map(function (n) {
        return parseInt(n, 10) || 0;
      });
    var pb = String(b || "0")
      .split(".")
      .map(function (n) {
        return parseInt(n, 10) || 0;
      });
    var len = Math.max(pa.length, pb.length);
    for (var i = 0; i < len; i++) {
      var x = pa[i] || 0;
      var y = pb[i] || 0;
      if (x > y) return 1;
      if (x < y) return -1;
    }
    return 0;
  }

  function getSeenVersion() {
    try {
      return localStorage.getItem(SEEN_KEY) || "";
    } catch (_) {
      return "";
    }
  }

  function markSeenVersion(version) {
    try {
      localStorage.setItem(SEEN_KEY, String(version || ""));
    } catch (_) {
      /* ignore */
    }
  }

  function shouldAutoShow(currentVersion) {
    if (!currentVersion) return false;
    var seen = getSeenVersion();
    if (!seen) return true;
    return compareVersions(currentVersion, seen) > 0;
  }

  function latestVersion() {
    return RELEASES[0] && RELEASES[0].version ? RELEASES[0].version : "";
  }

  function renderItem(item) {
    return (
      '<article class="whats-new-item">' +
      '<div class="whats-new-item-body">' +
      "<h4>" +
      escapeHtml(item.title) +
      "</h4>" +
      "<p>" +
      formatBodyHtml(item.body) +
      "</p>" +
      "</div></article>"
    );
  }

  function renderRelease(release) {
    var items = (release.items || []).map(renderItem).join("");
    return (
      '<section class="whats-new-release" data-version="' +
      escapeHtml(release.version) +
      '">' +
      '<header class="whats-new-release-head">' +
      '<p class="whats-new-version">Версия ' +
      escapeHtml(release.version) +
      "</p>" +
      "<h3>" +
      escapeHtml(release.title) +
      "</h3>" +
      (release.summary ? '<p class="whats-new-summary">' + escapeHtml(release.summary) + "</p>" : "") +
      "</header>" +
      '<div class="whats-new-items">' +
      items +
      "</div></section>"
    );
  }

  function renderWhatsNew(container, options) {
    if (!container) return;
    var opts = options || {};
    var appVersion = opts.appVersion || latestVersion();
    container.innerHTML =
      '<p class="whats-new-app-line">RM Client ' +
      escapeHtml(appVersion) +
      "</p>" +
      RELEASES.map(renderRelease).join("") +
      '<div class="whats-new-actions">' +
      '<button type="button" class="btn-primary" id="whats-new-ack-btn">Понятно</button>' +
      "</div>";
    container.classList.add("whats-new-root");
  }

